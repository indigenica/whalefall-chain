"""U15b (docs/preregistros/ESPEC_U15b.md): posteriors of the amplitude s (or f) from the MontePython chains, and verdict.

    python -B lya/u15b/analyze.py ~/u15b/chains           ->  lya/results/u15b/U15B_RESULT.json
    python -B lya/u15b/analyze.py ~/u15b/chains --check   ->  convergence only (what `run_wsl.sh status` shows); writes nothing

Until every case has R - 1 < 0.03 nothing about s is printed or written (ESPEC_U15b, Nota 5): the convergence test is the
same one the verdict uses, so `status` and `analyze` can no longer disagree.

Reads the MontePython chain files (<date>_<N>__<i>.txt: multiplicity, -lnL, parameters in the order of the .paramnames file
that `MontePython.py info` writes; if missing it is generated by calling info).
Per chain file: the non-Markovian part is removed per run (ESPEC_U15b Nota 9, lya/u15b/chainread.py: in each segment copied
from an earlier run, and in the new one, the points before that run's last '# ... update proposal' line), then the first 30 %
of what remains (Nota 2).  Files copied entirely into a restarted chain are skipped (Nota 3); forks are counted once.
With --check every case folder found is listed (U15b, U15c, ...); the U15b gate still uses only its own cases."""
import glob, json, os, subprocess, sys
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).resolve().parent))
import chainread

ROOT = Path(__file__).resolve().parents[2]; OUT = ROOT / "lya" / "results" / "u15b"
VAL = {"U15b_val_thermal_1keV": (1.0, 0.24), "U15b_val_thermal_2keV": (2.0, 0.38)}       # m, Hooper et al. eq. 4.1: f = 0.1 + m/7.2
ROWS = ["U15b_B2_R1.56_q1_x10_K0", "U15b_B2_R1.56_q1_x10_K1", "U15b_B2_R1.56_q1_x30_K0", "U15b_B2_R1.56_q1_x30_K1"]


def paramnames(folder):
    f = glob.glob(os.path.join(folder, "*.paramnames"))
    if not f:
        mp = os.environ.get("MP", str(Path.home() / "u15b" / "montepython_public"))
        subprocess.run([sys.executable, os.path.join(mp, "montepython", "MontePython.py"), "info", folder, "--noplot"], cwd=mp,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        f = glob.glob(os.path.join(folder, "*.paramnames"))
    if not f: return None
    return [l.split()[0] for l in open(f[0]) if l.strip()]


def wquantile(x, w, q):
    o = np.argsort(x); c = np.cumsum(w[o]); return float(np.interp(q * c[-1], c, x[o]))


def case(folder):
    names = paramnames(folder)
    if names is None: return dict(error="no chains yet (no .paramnames)")
    rows_all, rep = chainread.read(folder, len(names) + 2)          # Nota 9: per-run non-Markovian cut, copies and forks
    chains = []
    for rows in rows_all:
        a = np.array(rows)
        if len(a) < 20: continue
        chains.append(a[int(0.3 * len(a)):])
    dup = [r for r in rep if r["status"].startswith("copiado")]; forks = [r for r in rep if r["status"].startswith("bifurc")]
    n_nonmarkov = int(sum(r["points"] - r["kept"] for r in rep if not r["status"].startswith("copiado")))
    if not chains: return dict(error="no chains")
    j = 2 + names.index("s_tail")
    allc = np.vstack(chains); w = allc[:, 0]; s = allc[:, j]
    # Gelman-Rubin on every varying parameter (weighted means and variances per chain)
    def rminus1(col, cs):
        # Nota 6 (codex audit): a parameter frozen inside the chains but different between them is R-1 = inf, never NaN
        m = [np.average(c[:, col], weights=c[:, 0]) for c in cs]
        v = [np.average((c[:, col] - mm) ** 2, weights=c[:, 0]) for c, mm in zip(cs, m)]
        if len(cs) < 2: return float("inf")
        B = float(np.var(m, ddof=1)); W = float(np.mean(v))
        return B / W if W > 0 else (0.0 if B == 0 else float("inf"))
    halves = [h for c in chains for h in (c[:len(c) // 2], c[len(c) // 2:])]       # split-half R-1 (Gelman et al., BDA3)
    R = {n: rminus1(2 + i, chains) for i, n in enumerate(names) if np.std(allc[:, 2 + i]) > 0}
    R_split = {n: rminus1(2 + i, halves) for i, n in enumerate(names) if np.std(allc[:, 2 + i]) > 0}
    worst = sorted(R.items(), key=lambda kv: -np.nan_to_num(kv[1], nan=np.inf))[:3]
    hist, edges = np.histogram(s, bins=30, weights=w, density=True)
    # ESPEC_U15b Nota 4: "s = 0 outside the 95 %" read as outside the 95 % highest-posterior-density region (histogram)
    order = np.argsort(hist)[::-1]; mass = np.cumsum(hist[order] * np.diff(edges)[order])
    c95 = float(hist[order][np.searchsorted(mass, 0.95)])
    return dict(s0_outside_hpd95=bool(hist[0] < c95), p0_over_pmax=float(hist[0] / hist.max()),
                n_chains=len(chains), n_points=int(len(allc)), n_nonmarkovian_removed=int(n_nonmarkov), n_restart_copies_skipped=len(dup), n_forks=len(forks),
                n_points_per_chain=[int(len(c)) for c in chains], R_minus_1_worst=[[k, float(v)] for k, v in worst], s_95=wquantile(s, w, 0.95), s_mean=float(np.average(s, weights=w)),
                s_05=wquantile(s, w, 0.05), R_minus_1_max=rmax(R), R_minus_1=R,
                R_minus_1_split_max=rmax(R_split), ESS_s=ess(chains, j),
                min_chi2=float(2 * allc[:, 1].min()), posterior=dict(edges=edges.tolist(), density=hist.tolist()))


def finite(o):
    """strict JSON: inf/NaN written as null"""
    if isinstance(o, dict): return {k: finite(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)): return [finite(v) for v in o]
    if isinstance(o, float) and not np.isfinite(o): return None
    return o


def rmax(R):
    """largest R-1; any non-finite value (or no parameter at all) counts as not converged"""
    v = list(R.values())
    return float("inf") if not v or not all(np.isfinite(v)) else float(max(v))


def ess(chains, col):
    """effective sample size of one column, summed over chains (multiplicity-weighted, initial positive sequence of the ACF)"""
    tot = 0.0
    for c in chains:
        x = np.repeat(c[:, col], c[:, 0].astype(int)); n = len(x)
        if n < 4 or np.std(x) == 0: continue
        y = x - x.mean(); f = np.fft.rfft(y, 2 * n); acf = np.fft.irfft(f * np.conj(f))[:n]; acf /= acf[0]
        t = 1.0
        for k in range(1, n):
            if acf[k] <= 0: break
            t += 2 * acf[k]
        tot += n / t
    return float(tot)


N_CHAINS = 4                                        # per case (ESPEC_U15b; run_wsl.sh)


def converged(r):
    """Nota 6: finite R-1 < 0.03 in every parameter, split-half R-1 < 0.03, and exactly the expected number of chains (more would mean
    that a partial restart copy is being read as an independent chain, repeating points and lowering R-1: seen on 23 Oct in U15d)"""
    return bool(r.get("n_chains", 0) == N_CHAINS and r.get("R_minus_1_max", np.inf) < 0.03 and r.get("R_minus_1_split_max", np.inf) < 0.03)


ROWS_STOPPED = True                                 # ESPEC_U15b Nota 7 (16 Oct 2026): the four K_sw rows were stopped unread


S_KEYS = ("s_95", "s_05", "s_mean", "s0_outside_hpd95", "p0_over_pmax", "posterior")


def main(argv):
    check = "--check" in argv; argv = [a for a in argv if a != "--check"]
    base = argv[1] if len(argv) > 1 else str(Path.home() / "u15b" / "chains")
    out = dict(spec="docs/preregistros/ESPEC_U15b.md", cases={})
    found = sorted(os.path.basename(d) for d in glob.glob(os.path.join(base, "*")) if os.path.exists(os.path.join(d, "log.param")))
    for c in list(VAL) + ROWS + ([x for x in found if x not in VAL and x not in ROWS] if check else []):
        f = os.path.join(base, c)
        out["cases"][c] = case(f) if os.path.isdir(f) else dict(error="missing")
        r = out["cases"][c]
        if "error" in r: print(f"{c:28s} {r['error']}", flush=True); continue
        w = ", ".join(f"{k} {v:.3f}" for k, v in r["R_minus_1_worst"])
        extra = (f"  [{r['n_restart_copies_skipped']} copias saltadas" + (f", {r['n_forks']} bifurcaciones" if r['n_forks'] else "") + "]") if r['n_restart_copies_skipped'] or r['n_forks'] else ""
        print(f"{c:28s} {r['n_chains']} chains x {min(r['n_points_per_chain'])}-{max(r['n_points_per_chain'])} points (after cuts);"
              f"  max R-1 = {r['R_minus_1_max']:.3f} (split {r['R_minus_1_split_max']:.3f})  [{w}]{extra}", flush=True)
        if r["n_chains"] > N_CHAINS:                # a restart copy read as one more chain repeats points and lowers R-1 (23 Oct)
            print(f"{'':28s} AVISO: {r['n_chains']} cadenas, más de {N_CHAINS}: copias de una reanudación a medias o bifurcaciones "
                  "(run_wsl.sh diagnose); no cuenta como convergido", flush=True)
        elif r["n_chains"] < N_CHAINS:              # case() leaves out chains with fewer than 20 rows: a short or stopped chain
            print(f"{'':28s} AVISO: {r['n_chains']} cadenas con puntos suficientes, menos de {N_CHAINS}: alguna es aún corta o se paró; "
                  "no cuenta como convergido", flush=True)
    gate = list(VAL) if ROWS_STOPPED else list(out["cases"])               # Nota 7: physics rows stopped, only the validation gates
    conv = all(converged(out["cases"][c]) for c in gate)
    out["converged"] = bool(conv)
    if check:                                       # every case found with chains (U15c, U15d, ...), not only the U15b gate
        seen = [c for c in out["cases"] if c != "test" and not (ROWS_STOPPED and c in ROWS)]      # 'test': run_wsl.sh test, no chains
        left = [c for c in seen if "error" in out["cases"][c] or not converged(out["cases"][c])]      # missing or unreadable: not converged
        print("all cases converged (R-1 and split R-1 < 0.03, 4 chains): run analyze" if seen and not left else
              "not converged yet: " + ", ".join(left) + " (target: finite R-1 < 0.03 in every parameter, also split in halves, with 4 chains)")
        return
    OUT.mkdir(parents=True, exist_ok=True)
    if not conv:                                    # Nota 5: nothing about s before convergence
        for r in out["cases"].values():
            for k in S_KEYS: r.pop(k, None)
        out["verdict_U15b"] = ("PENDIENTE (validación sin converger; filas físicas detenidas, Nota 7)" if ROWS_STOPPED else
                               "PENDIENTE (cadenas sin converger: R-1 >= 0.03, R-1 por mitades >= 0.03 o un número de cadenas distinto de 4)")
        (OUT / "U15B_RESULT.json").write_text(json.dumps(finite(out), indent=1, allow_nan=False))
        print("U15b:", out["verdict_U15b"], flush=True)
        return
    for c in gate:
        print(f"{c:28s} s_95 = {out['cases'][c]['s_95']:.3f}", flush=True)
    v = {c: out["cases"][c].get("s_95") for c in VAL}
    out["validation"] = {c: dict(f_95=v[c], expected=VAL[c][1], ok=bool(v[c] is not None and 0.6 * VAL[c][1] <= v[c] <= 1.6 * VAL[c][1])) for c in VAL}
    val_ok = all(x["ok"] for x in out["validation"].values()) and v["U15b_val_thermal_1keV"] < v["U15b_val_thermal_2keV"]
    out["validation_passed"] = bool(val_ok)
    if ROWS_STOPPED:                                # Nota 7: no s of the physics rows is read or reported
        for c in ROWS:
            for k in S_KEYS: out["cases"].get(c, {}).pop(k, None)
        out["verdict_U15b"] = "DETENIDO (filas físicas superadas por U17-U21; validación " + ("PASA" if val_ok else "FALLA") + ")"
    elif not val_ok:
        out["verdict_U15b"] = "INCONCLUSO (validación)"
    else:
        st = {c: ("PERMITIDA" if out["cases"][c]["s_95"] >= 1 else "EXCLUIDA") for c in ROWS}
        out["rows"] = st
        out["verdict_U15b"] = ("COLA_TIBIA_PERMITIDA_LYA_COMPLETO" if all(x == "PERMITIDA" for x in st.values()) else
                               "COLA_TIBIA_EXCLUIDA_LYA_COMPLETO" if all(x == "EXCLUIDA" for x in st.values()) else "COLA_TIBIA_PARCIAL_LYA_COMPLETO")
        out["tail_preferred"] = {c: out["cases"][c]["s0_outside_hpd95"] for c in ROWS}     # Nota 4 (was s_05 > 0: always true)
    (OUT / "U15B_RESULT.json").write_text(json.dumps(finite(out), indent=1, allow_nan=False))
    print("U15b:", out["verdict_U15b"], flush=True)


if __name__ == "__main__":
    main(sys.argv)
